import { chromium } from "@playwright/test";

const base = process.env.M18_BASE_URL || "http://localhost:5273";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "tr-TR" });
const page = await context.newPage();
page.on("dialog", async (dialog) => { await dialog.accept(); });
await page.goto(`${base}/`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(900);
await page.locator('input[autocomplete="username"]').fill("room@demo.com");
await page.locator('input[autocomplete="current-password"]').fill("demo123");
await page.locator('button[type="submit"]').click();
await page.waitForTimeout(1100);
await page.goto(`${base}/#/room/drivers`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1100);
const tab = page.locator("button:visible").filter({ hasText: "Yönetim" }).first();
if (await tab.count()) await tab.click();
await page.waitForTimeout(450);
const details = page.locator("button:visible").filter({ hasText: "Yönetim detayları" }).first();
if (await details.count()) await details.click();
await page.waitForTimeout(900);
const row = page.locator("tr").filter({ hasText: "M18 CONT162 AUDIT DRIVER" }).last();
const action = row.getByRole("button", { name: "Cihaz sıfırla", exact: true });
const responsePromise = page.waitForResponse((r) => r.url().includes("/api/drivers/8/reset-device"), { timeout: 10000 }).catch(() => null);
await action.click();
const response = await responsePromise;
const payload = response ? await response.json().catch(() => ({})) : {};
await page.waitForTimeout(400);
const body = await page.locator("body").innerText();
console.log(JSON.stringify({ status: response?.status() || null, hadDeviceBinding: payload?.hadDeviceBinding ?? null, revokedSessions: payload?.revokedSessions ?? null, sessionVersionBumped: Number.isFinite(Number(payload?.sessionVersionBumpedTo)), visibleFeedback: /erişim sıfırlandı|Cihaz bağı ve aktif erişimler sıfırlandı/.test(body) }, null, 2));
await browser.close();
