#!/usr/bin/env node

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  GENERATED_PROJECTION_IDENTITY_MODE,
  RUN_SCOPED_GENERATED_EVIDENCE_IDENTITY_MODE,
  activeMilestoneTouchedPaths,
  readMilestoneOwnershipAuthority,
} from "./lib/milestoneOwnershipAuthority.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "../..");
const manifestPath = path.join(__dirname, "lib", "m18CopilotUiElementAnchorOwnershipManifest.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const entryByPath = new Map(manifest.entries.map((entry) => [entry.path, entry]));

const ledgerPaths = [
  "docs/LOCKED_INVARIANT_VIOLATION_LEDGER_V1.json",
  "docs/LOCKED_INVARIANT_VIOLATION_LEDGER_V1.md",
];
const commercialPath = "backend/src/routes/commercialCorePaymentReportsRoutes.js";

function expect(condition, message) {
  assert.equal(Boolean(condition), true, message);
}

function main() {
  const authority = readMilestoneOwnershipAuthority();
  const activePaths = new Set(activeMilestoneTouchedPaths(authority).map((entry) => entry.path));

  for (const ledgerPath of ledgerPaths) {
    const entry = entryByPath.get(ledgerPath);
    expect(entry, `missing generated ledger entry ${ledgerPath}`);
    expect(entry.identityMode === GENERATED_PROJECTION_IDENTITY_MODE, `ledger identity mode ${ledgerPath}`);
    expect(entry.projectionProducer === "backend/scripts/global_locked_invariant_suite_01_check.js", `ledger producer ${ledgerPath}`);
    expect(entry.projectionContract === "M18_CANONICAL_GENERATED_STATUS_PROJECTION_V1", `ledger contract ${ledgerPath}`);
    expect(/^[A-F0-9]{64}$/u.test(String(entry.historicalRawSha256 || "")), `ledger historical raw digest ${ledgerPath}`);
    expect(/^[A-F0-9]{64}$/u.test(String(entry.historicalNormalizedSha256 || "")), `ledger historical normalized digest ${ledgerPath}`);
  }

  const ledgerJson = JSON.parse(fs.readFileSync(path.join(repoRoot, ledgerPaths[0]), "utf8"));
  expect(ledgerJson.ledgerId === "LOCKED_INVARIANT_VIOLATION_LEDGER_V1", "ledger JSON identity marker");
  expect(typeof ledgerJson.generatedAt === "string" && ledgerJson.generatedAt.length > 0, "ledger JSON generation timestamp");
  expect(ledgerJson.currentSourceIdentity?.algorithm === "RAW_SHA256_PER_FILE", "ledger JSON source identity marker");
  expect(ledgerJson.ACTUAL_CURRENT_STATUS?.GLOBAL_LOCKED_INVARIANT_SUITE === "PASS", "ledger JSON current status marker");
  const ledgerMarkdown = fs.readFileSync(path.join(repoRoot, ledgerPaths[1]), "utf8");
  expect(ledgerMarkdown.includes("Generated by `global_locked_invariant_suite_01_check.js`"), "ledger Markdown producer marker");

  const frontendLog = entryByPath.get("m18-postrestart-frontend2.err.log");
  expect(frontendLog, "missing frontend runtime evidence entry");
  expect(frontendLog.identityMode === RUN_SCOPED_GENERATED_EVIDENCE_IDENTITY_MODE, "frontend log identity mode");
  expect(frontendLog.provenanceAuthority === "backend/scripts/lib/m18RunScopedProvenance.mjs", "frontend log provenance authority");
  expect(frontendLog.evidenceContract === "M18_RUN_SCOPED_FRONTEND_STDERR_EVIDENCE_V1", "frontend log evidence contract");
  expect(/^[A-F0-9]{64}$/u.test(String(frontendLog.historicalRawSha256 || "")), "frontend log historical raw digest");
  expect(/^[A-F0-9]{64}$/u.test(String(frontendLog.historicalNormalizedSha256 || "")), "frontend log historical normalized digest");

  expect(!activePaths.has(commercialPath), "PRE18 commercial route must not be an M18 active owner entry");
  const pre18 = authority.immutableClosure.manifest.touchedPaths.find((entry) => entry.path === commercialPath)
    || authority.immutableClosure.manifest.baselineStatusEntries.find((entry) => entry.path === commercialPath);
  expect(pre18 || fs.existsSync(path.join(repoRoot, commercialPath)), "commercial route must retain canonical historical evidence");

  console.log("M18_GOVERNANCE_IDENTITY_CONTRACT_STATUS=GREEN");
}

main();
